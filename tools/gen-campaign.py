# =============================================================================
# Campaign generator: draws all 12 levels as text grids and writes levels/drafts/<id>.mjs.
#   python3 tools/gen-campaign.py          then for each draft:   node tools/draft-level.mjs levels/drafts/<id>.mjs
# M(width, height) starts as solid wall; rect(...) carves floor, put(c, r, ch) places one character.
# Legend: # wall  . floor  H hedge  G gate  ~ carpet  ! squeaky  ^ > v < belts  o plate  | laser  = shield
#         P start  K key  I item  C checkpoint  L lever  T terminal  X sock (placed automatically)
# =============================================================================
import json, sys
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'levels', 'drafts') + '/'

class M:
    def __init__(s, w, h, fill='#'):
        s.w, s.h = w, h
        s.g = [[fill]*w for _ in range(h)]
    def rect(s, c0, r0, c1, r1, ch='.'):
        for r in range(r0, r1+1):
            for c in range(c0, c1+1): s.g[r][c] = ch
        return s
    def put(s, c, r, ch): s.g[r][c] = ch; return s
    def row(s, r, text, c0=0):
        for i, ch in enumerate(text): s.g[r][c0+i] = ch
        return s
    def rows(s): return [''.join(r) for r in s.g]
    def show(s):
        print('    ' + ''.join(str(c//10) for c in range(s.w)))
        print('    ' + ''.join(str(c%10) for c in range(s.w)))
        for i, r in enumerate(s.rows()): print(f'{i:3} {r}')

def hide_sock(m):
    """Put the sock in the dead end farthest (walking) from the start. Gates/lasers/shields count as passable."""
    from collections import deque
    rows = m.g
    walk = lambda c, r: 0 <= r < m.h and 0 <= c < m.w and rows[r][c] not in '#H'
    start = next((c, r) for r in range(m.h) for c in range(m.w) if rows[r][c] == 'P')
    dist = {start: 0}
    q = deque([start])
    while q:
        c, r = q.popleft()
        for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (c + dc, r + dr)
            if walk(*n) and n not in dist:
                dist[n] = dist[(c, r)] + 1
                q.append(n)
    def dead_end(c, r):
        return sum(walk(c + dc, r + dr) for dc, dr in ((1, 0), (-1, 0), (0, 1), (0, -1))) == 1
    spots = [p for p in dist if rows[p[1]][p[0]] == '.' and dead_end(*p)] or [p for p in dist if rows[p[1]][p[0]] == '.']
    c, r = max(spots, key=lambda p: (dist[p], -p[0], -p[1]))
    m.put(c, r, 'X')

def write(id, name, hint, par, m, aliens, alarmAfter=0, show=True):
    hide_sock(m)
    spec = dict(id=id, name=name, hint=hint, parTime=par, alarmAfter=alarmAfter, grid=m.rows(), aliens=aliens)
    open(OUT + id + '.mjs', 'w').write('// Generated by tools/gen-campaign.py; edit there (or polish the .tmj in Tiled).\nexport default ' + json.dumps(spec, indent=1) + ';\n')
    if show:
        print('==', id, name); m.show()

def A(kind, route, **kw):
    d = dict(kind=kind, route=[list(p) for p in route]); d.update(kw); return d

